"""
MTA Schemas — Pydantic models for System B.

Every input schema is extremely self-descriptive (P1) so that the LLM Agent
can understand each field's business meaning directly from the OpenAPI spec.

The AgentResponse envelope (P2, P4) wraps all outputs with explicit state
and allowed next actions.
"""
from __future__ import annotations

from pydantic import BaseModel, Field
from typing import Any, List, Optional
from datetime import datetime


# ================================================================
#  MTA Envelope (P2 Machine-Readable, P4 Explicit State)
# ================================================================

class AgentResponse(BaseModel):
    """
    The universal response envelope for every MTA tool.

    Every tool in System B returns this structure so that the Agent always
    knows: (1) what data was returned, (2) the current state of the entity,
    (3) what tools it is allowed to call next, and (4) how to recover if
    something went wrong.
    """
    data: Any = Field(
        description="The actual business data returned by this tool. "
                    "Its schema varies per tool — refer to each tool's docstring for details."
    )
    current_state: str = Field(
        description="The explicit current state of the primary entity involved in this operation. "
                    "Examples: 'pending', 'paid', 'shipped', 'delivered', 'refund_pending', 'refunded', 'cancelled'. "
                    "For product operations: 'active', 'deleted'. For list operations: 'list_result'."
    )
    allowed_next_tools: List[str] = Field(
        description="An ordered list of tool names that the Agent is permitted to call next, "
                    "given the current state. The Agent MUST NOT call tools outside this list "
                    "for the same entity."
    )
    error_guidance: Optional[str] = Field(
        default=None,
        description="If an error occurred, this field contains a natural-language instruction "
                    "telling the Agent exactly how to fix the problem. If null, the operation succeeded."
    )


