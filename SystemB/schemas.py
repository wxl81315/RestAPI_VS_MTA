class SearchProductsInput(BaseModel):
    """Input schema for the 'search_products' tool."""
    keyword: Optional[str] = Field(
        default=None,
        description="Optional keyword to filter products by name. "
                    "Leave empty or null to retrieve all products."
    )
    skip: int = Field(
        default=0,
        description="Number of records to skip for pagination. Default is 0 (start from the beginning)."
    )
    limit: int = Field(
        default=20,
        description="Maximum number of products to return. Default is 20. Maximum allowed is 100."
    )


